#!/usr/bin/env python3
"""Generates the Monarch launcher icon (vector XML + store PNGs) from one geometry source.

Run from the repo root: python3 tools/generate_icon.py
"""
from pathlib import Path
from PIL import Image, ImageDraw

SCALE, CY = 1.12, 48  # enlarge around the mark's centre, then centre it in the 108dp canvas
CROWN = [(34, 61), (34, 44), (44, 55), (54, 38), (64, 55), (74, 44), (74, 61)]
BAND = (34, 64, 74, 69, 2)  # left, top, right, bottom, corner radius
CREST = [(54, 27), (58, 31.5), (54, 36), (50, 31.5)]
CYAN, GOLD = "#00E5FF", "#FFC940"
BG_TOP, BG_BOTTOM = "#121A33", "#05060D"

def t(x, y): return round(54 + (x - 54) * SCALE, 2), round(54 + (y - CY) * SCALE, 2)
def poly_path(pts): return "M" + " L".join(f"{x},{y}" for x, y in (t(*p) for p in pts)) + " Z"
def band_path():
    (l, tp), (r, b) = t(BAND[0], BAND[1]), t(BAND[2], BAND[3])
    c = round(BAND[4] * SCALE, 2)
    return (f"M{l + c},{tp} L{r - c},{tp} A{c},{c} 0 0 1 {r},{tp + c} L{r},{b - c} A{c},{c} 0 0 1 {r - c},{b} "
            f"L{l + c},{b} A{c},{c} 0 0 1 {l},{b - c} L{l},{tp + c} A{c},{c} 0 0 1 {l + c},{tp} Z")

HEAD = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/generate_icon.py. {note} -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp"\n'
        '    android:height="108dp"\n    android:viewportWidth="108"\n    android:viewportHeight="108">\n')
def path(color, data): return f'    <path\n        android:fillColor="{color}"\n        android:pathData="{data}" />\n'

res = Path("app/src/main/res/drawable")
res.joinpath("ic_launcher_foreground.xml").write_text(
    HEAD.format(note="Geometric M-crown with a gold crest, inside the 66dp safe zone.")
    + path(CYAN, poly_path(CROWN)) + path(CYAN, band_path()) + path(GOLD, poly_path(CREST)) + "</vector>\n")
res.joinpath("ic_launcher_monochrome.xml").write_text(
    HEAD.format(note="Single-colour mark for Android 13+ themed icons.")
    + path("#FFFFFFFF", " ".join([poly_path(CROWN), band_path(), poly_path(CREST)])) + "</vector>\n")

def hex2rgb(h): return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))
def render(size, out, mask=None):
    ss = size * 4; k = ss / 108
    img = Image.new("RGB", (ss, ss)); d = ImageDraw.Draw(img)
    a, b = hex2rgb(BG_TOP), hex2rgb(BG_BOTTOM)
    for y in range(ss):
        f = y / (ss - 1); d.line([(0, y), (ss, y)], fill=tuple(round(p + (q - p) * f) for p, q in zip(a, b)))
    P = lambda pts: [tuple(v * k for v in t(*p)) for p in pts]
    d.polygon(P(CROWN), fill=hex2rgb(CYAN))
    (l, tp), (r, bt) = t(BAND[0], BAND[1]), t(BAND[2], BAND[3])
    d.rounded_rectangle([l * k, tp * k, r * k, bt * k], radius=BAND[4] * SCALE * k, fill=hex2rgb(CYAN))
    d.polygon(P(CREST), fill=hex2rgb(GOLD))
    img = img.resize((size, size), Image.LANCZOS)
    if mask == "circle":
        m = Image.new("L", (size, size), 0); ImageDraw.Draw(m).ellipse([0, 0, size, size], fill=255)
        out_img = Image.new("RGBA", (size, size), (0, 0, 0, 0)); out_img.paste(img, (0, 0), m); img = out_img
    img.save(out)

Path("docs/images").mkdir(parents=True, exist_ok=True)
render(512, "docs/images/icon-512.png")
render(512, "docs/images/icon-round.png", mask="circle")
print("icon generated")
