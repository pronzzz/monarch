package com.antigravity.monarch.domain.model

import kotlinx.serialization.KSerializer
import kotlinx.serialization.Serializable
import kotlinx.serialization.descriptors.PrimitiveKind
import kotlinx.serialization.descriptors.PrimitiveSerialDescriptor
import kotlinx.serialization.encoding.Decoder
import kotlinx.serialization.encoding.Encoder
import java.time.DayOfWeek

enum class PlanSource(val displayName: String) {
    RULES("The System (on-device)"),
    LLM("The System (cloud AI)"),
}

/** How the previous fortnight of adherence changes next week's plan. */
@Serializable
enum class AdaptationDirection(val volumeMultiplier: Double, val extraSets: Int) {
    DELOAD(0.8, -1),
    HOLD(1.0, 0),
    PROGRESS(1.1, 1),
}

@Serializable
data class PlanAdaptation(
    val direction: AdaptationDirection = AdaptationDirection.HOLD,
    val completionRate: Double? = null,
    val plannedSessions: Int = 0,
    val completedSessions: Int = 0,
    val note: String = "",
) {
    companion object {
        val NEUTRAL = PlanAdaptation(note = "First plan: calibrated from your onboarding answers.")
    }
}

@Serializable
data class PlanExercise(
    val name: String,
    val sets: Int? = null,
    val reps: String? = null,
    val durationMinutes: Int? = null,
    val notes: String? = null,
) {
    fun prescription(): String = when {
        sets != null && reps != null -> "$sets × $reps"
        durationMinutes != null -> "$durationMinutes min"
        sets != null -> "$sets sets"
        else -> ""
    }
}

@Serializable
data class PlanDay(
    @Serializable(with = DayOfWeekSerializer::class) val day: DayOfWeek,
    val title: String,
    val workoutType: WorkoutType,
    val targetMinutes: Int,
    val exercises: List<PlanExercise>,
)

@Serializable
data class WorkoutPlan(
    val title: String,
    val summary: String,
    val days: List<PlanDay>,
    val source: PlanSource,
    val adaptation: PlanAdaptation = PlanAdaptation.NEUTRAL,
    /** ISO date (Monday) of the week this plan was generated for. */
    val weekStart: String,
    val generatedAtEpochMs: Long,
) {
    fun dayFor(day: DayOfWeek): PlanDay? = days.firstOrNull { it.day == day }
    val workoutDays: Set<DayOfWeek> get() = days.map { it.day }.toSet()
}

@Serializable
data class MealIdea(val meal: String, val idea: String)

/**
 * General nutrition guidance. Numbers are always computed deterministically on-device from
 * standard formulas; they are estimates, not medical advice.
 */
@Serializable
data class DietGuideline(
    val dailyCalories: Int,
    val proteinGrams: Int,
    val carbsGrams: Int,
    val fatGrams: Int,
    val waterMl: Int,
    val tips: List<String>,
    val mealIdeas: List<MealIdea>,
)

@Serializable
data class GeneratedPlan(
    val workout: WorkoutPlan,
    val diet: DietGuideline,
)

const val HEALTH_DISCLAIMER =
    "Monarch provides general fitness and nutrition guidance generated by software, including AI. " +
        "It is not medical advice. Check with a qualified professional before starting a new " +
        "exercise or diet programme, especially if you have a health condition. Stop if you feel pain."

object DayOfWeekSerializer : KSerializer<DayOfWeek> {
    override val descriptor = PrimitiveSerialDescriptor("DayOfWeek", PrimitiveKind.STRING)
    override fun serialize(encoder: Encoder, value: DayOfWeek) = encoder.encodeString(value.name)
    override fun deserialize(decoder: Decoder): DayOfWeek = DayOfWeek.valueOf(decoder.decodeString().uppercase())
}
